import type { CaseDefinition, DecisionLogEntry } from './types';
import { compareToBestPath } from './best-path';
import { gradeForRatio, totalScoreFromLog } from './scoring';
import { tr, type Locale } from './i18n';

export interface LessonPlanInput {
  caseDef: CaseDefinition;
  log: DecisionLogEntry[];
  elapsedGameMin: number;
  totalCostSGD: number;
  burden?: { timeOffWorkHours: number; financialWorry: number; sleepDebt: number };
  profile?: { name: string; wardClass: string; chasTier: string; hasIntegratedShield: boolean };
  /** Locale to resolve LocalisedString fields with. Defaults to English. */
  locale?: Locale;
  /** Per-decision learner reflection notes, keyed by decisionId. Surfaced
   *  as a blockquote after each decision in the exported lesson plan. */
  notes?: Record<string, string>;
  /** Ordered node ids the patient visited. When supplied, a "Patient journey"
   *  section lists each stop with its facility + department + staff-perspective
   *  framing so the export reads as a clinical narrative, not just a decision
   *  list. */
  journey?: string[];
}

