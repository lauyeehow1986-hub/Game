/**
 * Generate a markdown lesson-plan summary of a completed run. Educators paste
 * it into their teaching notes, a Google Doc, Notion, etc. — every decision
 * is shown with the chosen option, the best-practice option, both rationales,
 * and the reference guideline.
 */
export function generateLessonPlan(input: LessonPlanInput): string {
  const { caseDef, log, elapsedGameMin, totalCostSGD, burden, profile } = input;
  const loc = input.locale ?? 'en';
  const S = STRINGS[loc] ?? STRINGS.en;
  const L = (v: unknown) => tr(v as Parameters<typeof tr>[0], loc);
  const { earned, max } = totalScoreFromLog(log);
  const ratio = max > 0 ? earned / max : 0;
  const grade = gradeForRatio(ratio);
  const diff = compareToBestPath(caseDef, log);

  const lines: string[] = [];
  lines.push(`# ${L(caseDef.title)}`);
  lines.push('');
  if (caseDef.historical) lines.push(`> ${S.histDisclaimer}`);
  lines.push(L(caseDef.blurb));
  lines.push('');
  lines.push(`## ${S.summary}`);
  lines.push(`- **${S.score}**: ${earned.toFixed(1)} / ${max.toFixed(1)} — **${grade.grade}** (${(ratio * 100).toFixed(0)}%)`);
  lines.push(`- **${S.inGameTime}**: ${fmtDuration(elapsedGameMin, S)}`);
  lines.push(`- **${S.cashOop}**: S$${totalCostSGD.toFixed(0)}`);
  lines.push(`- **${S.decisionsMade}**: ${log.length}`);
  if (profile) {
    lines.push(
      `- **${S.patient}**: ${profile.name} · ${S.ward} ${profile.wardClass} · CHAS ${
        profile.chasTier === 'none' ? S.chasNone : profile.chasTier
      }${profile.hasIntegratedShield ? ` · ${S.ipRider}` : ''}`,
    );
  }
  if (burden) {
    lines.push(
      `- **${S.caregiverBurden}**: ${burden.timeOffWorkHours.toFixed(0)}${S.hOffWork} · ${S.worry} ${burden.financialWorry.toFixed(0)}/100 · ${S.sleepDebt} ${burden.sleepDebt.toFixed(0)}/100`,
    );
  }
  lines.push('');

  if (input.journey && input.journey.length > 0) {
    const stops = input.journey
      .map((id) => caseDef.pathway.find((n) => n.id === id))
      .filter((n): n is NonNullable<typeof n> => n != null);
    const rendered: string[] = [];
    for (const n of stops) {
      const framing = L(n.framing.staff);
      if (!framing) continue;
      rendered.push(`- **${n.facility ?? caseDef.primaryFacility}** · ${n.department} — ${framing}`);
    }
    if (rendered.length > 0) {
      lines.push(`## ${S.patientJourney}`);
      lines.push(...rendered);
      lines.push('');
    }
  }

  if (diff.length > 0) {
    lines.push(`## ${S.decisions}`);
    diff.forEach((row, i) => {
      lines.push(`### ${i + 1}. ${L(row.prompt)}`);
      if (row.yours) {
        lines.push(`- **${S.chosen}**: ${L(row.yours.label)} — ${row.yours.score.toFixed(1)} / ${row.yours.maxScore.toFixed(1)} ${S.pts}`);
      }
      lines.push(`- **${S.bestPractice}**: ${L(row.best.label)} — ${row.best.score.toFixed(1)} ${S.pts}`);
      lines.push(row.match ? `- *${S.matched}*` : `- *${S.differs}*`);
      const node = caseDef.pathway.find((n) => n.decision?.id === row.decisionId);
      // Match by resolved label so we find the option regardless of locale.
      const chosen = node?.decision?.options.find((o) => L(o.label) === L(row.yours?.label));
      const best = node?.decision?.options.find((o) => L(o.label) === L(row.best.label));
      if (chosen?.rationale) lines.push(`- ${S.rationaleChosen}: ${L(chosen.rationale)}`);
      if (best?.rationale && best !== chosen) lines.push(`- ${S.rationaleBest}: ${L(best.rationale)}`);
      if (node?.decision?.reference?.label) lines.push(`- ${S.reference}: *${L(node.decision.reference.label)}*`);
      const note = input.notes?.[row.decisionId]?.trim();
      if (note) {
        lines.push('');
        for (const ln of note.split(/\r?\n/)) lines.push(`> ${ln}`);
      }
      lines.push('');
    });
  }

  if (caseDef.guidelines.length > 0) {
    lines.push(`## ${S.references}`);
    for (const g of caseDef.guidelines) {
      lines.push(`- **${L(g.label)}** — ${L(g.body)}`);
    }
    lines.push('');
  }

  if (caseDef.historical && caseDef.citations && caseDef.citations.length > 0) {
    lines.push(`## ${S.histCitations}`);
    caseDef.citations.forEach((c, i) => lines.push(`${i + 1}. ${c}`));
    lines.push('');
  }

  lines.push('---');
  lines.push(S.footer);

  return lines.join('\n');
}

function fmtDuration(min: number, S: LessonPlanStrings): string {
  const h = Math.floor(min / 60);
  const d = Math.floor(h / 24);
  const rh = h % 24;
  const rm = min % 60;
  if (d > 0) return `${d}${S.d} ${rh}${S.h}`;
  if (h > 0) return `${h}${S.h} ${rm}${S.m}`;
  return `${min}${S.m}`;
}
